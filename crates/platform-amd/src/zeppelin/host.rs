//! Zeppelin host compiler and image policy.
//!
//! One DRAM stage, the BIOS reset image the PSP copies, runs from reset vector
//! to payload. The payload and its manifest go into an FFS between the vendor
//! PSP prefix and the reset image. The vendor flash image is the explicit
//! `--image-config` input: its BIOS directory must describe the reset image and
//! APOB destination this layout was linked for.
extern crate std;
use super::layout as l;
use fstart_core::{
    hstr,
    BoardBuildPolicy, FirmwareImageConfig, FirmwareImagePolicy, MemoryRegion, MonolithicConfig,
    PayloadConfig, Platform, SocImageFormat, StageBuildConfig, StageLayout, layout::RegionKind,
};
use fstart_image_build::{
    amd::vendor_flash::{VendorFlashAssembly, VendorFlashLayout, read_bios_directory},
    build_plan::{
        Assembly, BuildPlan, CargoTarget, CompilationUnit, CompilerCfgSchema, FfsAssembly,
        FileBinding, InputFile, UnitOutput,
    },
    elf::{Architecture, Descriptor, Expectations},
    layout::EncodedLayout,
    plan::{BuildSelection, Span},
};
use std::{
    collections::BTreeMap,
    format,
    string::{String, ToString},
    vec,
    vec::Vec,
};

pub const ENTRY: &str = "amd-psp-reset";
const UNIT: &str = "stage";
/// Up to 32 threads (two dies of eight SMT cores).
const MAX_CPUS: u16 = 32;

pub struct Plan<B>(core::marker::PhantomData<B>);
impl<B: super::Board> Plan<B> {
    pub fn emit(selection_json: &str) {
        let selection: BuildSelection =
            serde_json::from_str(selection_json).expect("invalid build selection");
        let plan = resolve::<B>(selection).expect("invalid Zeppelin build plan");
        std::println!(
            "{}",
            serde_json::to_string(&plan).expect("serialize Zeppelin plan")
        );
    }
}

/// Check the explicit vendor image against the layout this stage is linked for.
fn vendor_layout(path: &str) -> Result<(FileBinding, VendorFlashLayout), String> {
    let bytes = std::fs::read(path).map_err(|e| format!("vendor image {path}: {e}"))?;
    if bytes.len() != l::FLASH_SIZE as usize {
        return Err(format!(
            "vendor image {path} is {:#x} bytes, the flash {:#x}",
            bytes.len(),
            l::FLASH_SIZE
        ));
    }
    let facts = read_bios_directory(&bytes, l::VENDOR_PREFIX)?;
    let layout = VendorFlashLayout {
        flash_size: l::FLASH_SIZE,
        prefix_size: l::VENDOR_PREFIX,
        ffs_offset: l::FFS_OFFSET,
        ffs_size: l::FFS_SIZE,
        reset_offset: l::RESET_FLASH_OFFSET,
        reset_size: l::IMAGE_SIZE as u32,
        reset_destination: l::IMAGE_BASE,
        apob_destination: fstart_driver_amd::zeppelin::APOB_BASE,
    };
    layout.validate()?;
    if (facts.reset_offset, facts.reset_size, facts.reset_destination, facts.apob_destination)
        != (
            layout.reset_offset,
            layout.reset_size,
            layout.reset_destination,
            layout.apob_destination,
        )
    {
        return Err(format!(
            "vendor BIOS directory {facts:?} doesn't match the Zeppelin layout {layout:?}"
        ));
    }
    Ok((
        FileBinding {
            environment: "VENDOR_FLASH".into(),
            path: path.into(),
            capacity: u64::from(l::FLASH_SIZE),
        },
        layout,
    ))
}

fn linker_script(descriptor: &EncodedLayout) -> String {
    let data_size = l::HEAP_START - l::DATA_START;
    let stack_size = l::STACK_TOP - l::STACK_BOTTOM;
    format!(
        r#"/* Generated by fstart-platform-amd: Zeppelin PSP DRAM reset image. */
OUTPUT_FORMAT(elf64-x86-64)
OUTPUT_ARCH(i386:x86-64)
ENTRY(_start)
MEMORY {{
    image (rwx) : ORIGIN = {image:#x}, LENGTH = {image_size:#x}
    data (rw) : ORIGIN = {data:#x}, LENGTH = {data_size:#x}
    heap (rw) : ORIGIN = {heap:#x}, LENGTH = {heap_size:#x}
    stack (rw) : ORIGIN = {stack:#x}, LENGTH = {stack_size:#x}
}}
_fstart_page_tables = {page_tables:#x};
_fstart_early_reserved_start = {early:#x};
_fstart_early_reserved_end = {early_end:#x};
SECTIONS {{
    .text {image:#x} : {{
        _text_start = .;
        KEEP(*(.text.entry))
        *(.text .text.* .ltext .ltext.*)
    }} > image
{layout}    .rodata : ALIGN(16) {{
        *(.rodata .rodata.* .lrodata .lrodata.*)
        KEEP(*(.fstart.keep))
    }} > image    .fstart.anchor : ALIGN(16) {{
        _fstart_anchor_early = .;
        KEEP(*(.fstart.anchor))
        _fstart_early_microcode_enabled = .;
        LONG(0)
        . = ALIGN(8);
        _FSTART_HEAP_SIZE = .;
        QUAD({heap_size:#x})
    }} > image
    .got : ALIGN(8) {{ *(.got) *(.got.plt) }} > image    .data : ALIGN(16) {{
        _data_start = .;
        *(.data .data.* .ldata .ldata.*)
        . = ALIGN(16);
        _data_end = .;
    }} > data AT > image
    _data_load = LOADADDR(.data);
    _fstart_text_end = LOADADDR(.data) + SIZEOF(.data);
    _binary_end = _fstart_text_end;
    .bss (NOLOAD) : ALIGN(16) {{
        _bss_start = .;
        _fstart_bss_start = .;
        *(.bss .bss.* .lbss .lbss.*)
        *(COMMON)
        . = ALIGN(16);
        _bss_end = .;
        _fstart_bss_end = .;
    }} > data
    .fstart.heap (NOLOAD) : ALIGN(16) {{
        _FSTART_HEAP = .;
        . = . + {heap_size:#x};
    }} > heap
    .stack (NOLOAD) : ALIGN(16) {{
        _stack_bottom = .;
        _fstart_stack_bottom = .;
        . = . + {stack_size:#x};
        _stack_top = .;
        _fstart_stack_top = .;
        _writable_end = .;
    }} > stack
    .init16 {init16:#x} : {{ KEEP(*(.init16)) }} > image
    .reset {reset:#x} : {{ KEEP(*(.reset)) }} > image
    .last_byte {last:#x} : {{ BYTE(0xff); }} > image
    .unsupported_dynamic : {{ *(.dynamic) }} > image
    .unsupported_rel : {{ *(.rel.*) *(.rela.*) *(.relr.*) }} > image
    .unsupported_loader : {{ *(.interp .plt .plt.* .iplt) }} > image
    /DISCARD/ : {{ *(.eh_frame*) *(.comment*) *(.note*) }}
}}
_fstart_gdt_offset = _fstart_gdt_pointer & 0xffff;
/* The architectural CAR entry is linked but never runs: no Cache-as-RAM. */
_has_car = 0;
_car_base = 0;
_car_size = 0;
_ecar_stack = _stack_top;
_rom_mtrr_base = 0;
_rom_mtrr_mask = 0;
ASSERT(SIZEOF(.unsupported_dynamic) + SIZEOF(.unsupported_rel) + SIZEOF(.unsupported_loader) == 0, "the reset image can't require runtime linking")
ASSERT(_fstart_text_end <= ADDR(.init16), "code and data exceed the PSP reset image")
ASSERT(ADDR(.init16) + SIZEOF(.init16) <= ADDR(.reset), "16-bit entry overflows the reset vector")
ASSERT(SIZEOF(.reset) <= 15, "reset vector too large")
ASSERT(_bss_end <= ORIGIN(heap), "data and BSS exceed their reservation")
"#,
        image = l::IMAGE_BASE,
        image_size = l::IMAGE_SIZE,
        data = l::DATA_START,
        heap = l::HEAP_START,
        heap_size = l::HEAP_SIZE,
        stack = l::STACK_BOTTOM,
        page_tables = l::PAGE_TABLES,
        early = l::EARLY_START,
        early_end = l::EARLY_END,
        init16 = l::IMAGE_END - 0x2000,
        reset = l::RESET_VECTOR,
        last = l::IMAGE_END - 1,
        layout = fstart_image_build::linker::layout_section(descriptor, "image"),
    )
}

pub fn resolve<B: super::Board>(selection: BuildSelection) -> Result<BuildPlan, String> {
    selection.validate_compiler_files()?;
    if !selection.compiler_files.is_empty() {
        return Err("Zeppelin takes no compiler inputs".into());
    }
    let requested = selection.payload.clone().unwrap_or_else(|| "halt".into());
    if selection.has_x86_linux_overrides() && requested != "linux" {
        return Err("x86 Linux options require '--payload linux'".into());
    }
    let (payload, feature, payload_config): (&str, Option<&str>, Option<PayloadConfig>) =
        match requested.as_str() {
            "halt" => ("halt", None, None),
            "linux" => (
                "linux",
                Some("payload-linux"),
                Some(
                    fstart_core::x86_linux_payload(
                        selection
                            .x86_linux_kernel_load_addr
                            .unwrap_or(fstart_core::payload_manifest::X86_LINUX_DEFAULT_KERNEL_LOAD_ADDR),
                        fstart_core::payload_manifest::X86_LINUX_DEFAULT_ZERO_PAGE_ADDR,
                        selection.x86_linux_bootargs.as_deref().unwrap_or(""),
                        selection.x86_linux_print_mtrrs,
                    )
                    .map_err(ToString::to_string)?,
                ),
            ),
            "uefi" => (
                "crabefi",
                Some("payload-uefi"),
                Some(fstart_core::x86_uefi_payload()),
            ),
            "uefi-basic" => (
                "crabefi",
                Some("payload-uefi-basic"),
                Some(fstart_core::x86_uefi_payload()),
            ),
            other => return Err(format!("Zeppelin supports halt, linux and uefi, not {other}")),
        };

    let image = Span {
        base: l::IMAGE_BASE,
        size: l::IMAGE_SIZE,
    };
    let writable = Span {
        base: l::DATA_START,
        size: l::STACK_TOP - l::DATA_START,
    };
    let stack = Span {
        base: l::STACK_BOTTOM,
        size: l::STACK_TOP - l::STACK_BOTTOM,
    };
    let heap = Span {
        base: l::HEAP_START,
        size: l::HEAP_SIZE,
    };
    let flash = Span {
        base: l::FLASH_BASE,
        size: u64::from(l::FLASH_SIZE),
    };
    let ffs_window = Span {
        base: l::FFS_BASE,
        size: u64::from(l::FFS_SIZE),
    };
    let descriptor = EncodedLayout::encode(
        0,
        &[
            image.region(RegionKind::Image),
            flash.region(RegionKind::Flash),
            ffs_window.region(RegionKind::Firmware),
            writable.region(RegionKind::Writable),
            stack.region(RegionKind::Stack),
            heap.region(RegionKind::Heap),
        ],
    )
    .map_err(|e| e.to_string())?;
    let expectations = Expectations {
        architecture: Architecture::X86_64,
        elf64: true,
        little_endian: true,
        stored: vec![image],
        runtime: vec![image, writable],
        identity_mapping: false,
        entry: Some(l::RESET_VECTOR),
        copy: None,
        descriptor: Some(Descriptor {
            section: ".fstart.layout".into(),
            start_symbol: "_fstart_layout_start".into(),
            end_symbol: "_fstart_layout_end".into(),
            bytes: descriptor.as_bytes().to_vec(),
            reservation: image,
        }),
        stored_flags: None,
        symbols: BTreeMap::from([
            ("_start".into(), l::RESET_VECTOR),
            ("_fstart_page_tables".into(), l::PAGE_TABLES),
            ("_FSTART_HEAP".into(), l::HEAP_START),
            ("_stack_bottom".into(), l::STACK_BOTTOM),
            ("_stack_top".into(), l::STACK_TOP),
        ]),
    };
    expectations.validate()?;

    let ffs = FfsAssembly {
        platform: Platform::X86_64,
        memory: vec![
            MemoryRegion {
                name: hstr("flash"),
                base: l::FLASH_BASE,
                size: u64::from(l::FLASH_SIZE),
                kind: fstart_core::RegionKind::Rom,
            },
            MemoryRegion {
                name: hstr("dram"),
                base: l::EARLY_START,
                size: l::EARLY_END - l::EARLY_START,
                kind: fstart_core::RegionKind::Ram,
            },
        ],
        flash: None,
        bootstrap: vec![],
        stages: StageLayout::Monolithic(MonolithicConfig {
            build: StageBuildConfig {
                firmware_image: Some(FirmwareImageConfig {
                    temp_ram_buffer: None,
                }),
                verify_firmware: true,
                payload: payload != "halt",
                pci: true,
                ..Default::default()
            },
            load_addr: l::IMAGE_BASE,
            data_addr: Some(l::DATA_START),
            stack_size: (l::STACK_TOP - l::STACK_BOTTOM) as u32,
            heap_size: Some(l::HEAP_SIZE as u32),
            page_table_addr: None,
            page_size: Default::default(),
            external: true,
        }),
        security: fstart_core::dev_security_config("keys/dev-signing.pub"),
        payload: payload_config,
        microcode: None,
        data_assets: vec![],
        full_flash_image: false,
        soc_image_format: SocImageFormat::None,
        boot_hart_id: 0,
        build: BoardBuildPolicy {
            firmware_image: FirmwareImagePolicy::memory_mapped(l::FFS_BASE, u64::from(l::FFS_SIZE)),
            ..Default::default()
        },
    };
    let inputs: Vec<InputFile> = if payload == "linux" {
        vec![InputFile {
            name: "kernel".into(),
            default: None,
            capacity: u64::from(l::FFS_SIZE),
        }]
    } else {
        vec![]
    };
    let assembly = match &selection.image_config {
        Some(path) => {
            let (vendor, layout) = vendor_layout(path)?;
            Assembly::VendorFlash(std::boxed::Box::new(VendorFlashAssembly {
                ffs,
                vendor,
                layout,
                reset_unit: UNIT.into(),
            }))
        }
        None => Assembly::Ffs(std::boxed::Box::new(ffs)),
    };
    let plan = BuildPlan {
        payload: payload.into(),
        stages: vec![UNIT.into()],
        inputs,
        assembly,
        units: vec![CompilationUnit {
            name: UNIT.into(),
            cargo_target: CargoTarget::BoardBinary,
            target: "x86_64-unknown-none".into(),
            entry: ENTRY.into(),
            environment: "monolithic".into(),
            payload: payload.into(),
            cfg_schema: CompilerCfgSchema {
                entries: vec![ENTRY.into()],
                environments: vec!["monolithic".into()],
                payloads: vec!["halt".into(), "linux".into(), "crabefi".into()],
            },
            features: core::iter::once("bundle-zeppelin")
                .chain(feature)
                .map(String::from)
                .collect(),
            build_std: None,
            rustflags: vec![
                "-Zub-checks=no".into(),
                "-Crelocation-model=static".into(),
                "-Cno-redzone=yes".into(),
                "--cfg".into(),
                "curve25519_dalek_backend=\"serial\"".into(),
            ],
            release_only: false,
            linker_script: Some(linker_script(&descriptor)),
            environment_values: BTreeMap::from([(
                "FSTART_MP_MAX_CPUS".into(),
                MAX_CPUS.to_string(),
            )]),
            bindings: vec![],
            file_bindings: vec![],
            output: UnitOutput::Executable {
                expectations,
                load_address: image.base,
                flat_capacity: image.size,
            },
        }],
    };
    plan.order()?;
    plan.validate_compiler_selections(&selection)?;
    plan.validate_image_selection(&selection)?;
    Ok(plan)
}
