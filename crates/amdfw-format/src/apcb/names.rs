/// The tokens that program fuses (Platform Secure Boot, OPN platform
/// compatibility): a build may only *update* them where an APCB already
/// carries them, never add them, and overlays must never enable them.
/// Sorted by ID.
pub const IN_PLACE_ONLY: &[u32; 2] = &[
    0x24b45ecd, // PspOpnPlatformComptFusing
    0x2fcd70c9, // PspPsbAutoFuse
];

/// Whether token `id` is one of [`IN_PLACE_ONLY`].
pub fn in_place_only(id: u32) -> bool {
    IN_PLACE_ONLY.binary_search(&id).is_ok()
}

/// The ID of token `name` (a name or an alias).
pub fn id(name: &str) -> Option<u32> {
    NAMES
        .iter()
        .find(|(_, n, _)| *n == name)
        .map(|&(id, ..)| id)
}

/// The name of token `id`.
pub fn name(id: u32) -> Option<&'static str> {
    let at = NAMES.partition_point(|&(t, ..)| t < id);
    NAMES
        .get(at)
        .filter(|&&(t, ..)| t == id)
        .map(|&(_, n, _)| n)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_sorted_unique_and_found_both_ways() {
        assert!(NAMES.windows(2).all(|w| w[0].0 <= w[1].0));
        for (i, (_, a, _)) in NAMES.iter().enumerate() {
            assert!(NAMES[i + 1..].iter().all(|(_, b, _)| a != b), "{a}");
        }
        assert_eq!(id("DfPciMmioSize"), Some(0x3d9b_7d7b));
        assert_eq!(id("CbsDfDbgNumPciSegments"), Some(0x3d9b_7d7b));
        assert_eq!(name(0x3d9b_7d7b), Some("DfPciMmioSize"));
        assert_eq!(id("BmcSocket"), Some(0x8465_73f9));
        assert_eq!(id("MemTsmeModeMilan"), Some(0xd1fa_6660));
        assert_eq!(name(0), None);
        assert_eq!(id("NoSuchToken"), None);
    }

    #[test]
    fn the_fusing_tokens_are_in_place_only() {
        assert!(IN_PLACE_ONLY.windows(2).all(|w| w[0] < w[1]));
        assert_eq!(
            IN_PLACE_ONLY.map(name),
            [Some("PspOpnPlatformComptFusing"), Some("PspPsbAutoFuse")]
        );
        assert!(in_place_only(id("PspPsbAutoFuse").unwrap()));
        assert!(!in_place_only(id("DfPciMmioSize").unwrap()));
    }
}
