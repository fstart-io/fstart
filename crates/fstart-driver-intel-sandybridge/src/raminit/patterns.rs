pub fn fill_pattern5(mchbar_base: usize, state: &RaminitState, channel: usize, patno: usize) {
    let offset = preceding_channels(state, channel) * 64;
    let step = 64 * num_channels(state);
    if patno == 0 {
        for (i, row) in PATTERN.iter().enumerate() {
            for (j, val) in row.iter().copied().enumerate() {
                write_pattern32(WDB_BASE + offset + i * step + j * 4, val);
            }
        }
    } else {
        let pat = (patno - 1) % (NUM_PATTERNS - 1);
        let base8 = 0x80u8 >> ((patno - 1) % 8);
        let base = u32::from(base8) * 0x0101_0101;
        for i in 0..32usize {
            for j in 0..16usize {
                let mut val = if (USE_BASE[pat][i] & (1 << (j / 2))) != 0 {
                    base
                } else {
                    0
                };
                if (INVERT[pat][i] & (1 << (j / 2))) != 0 {
                    val = !val;
                }
                write_pattern32(WDB_BASE + offset + i * step + j * 4, val);
            }
        }
    }
    compiler_fence(Ordering::SeqCst);
    program_wdb_pattern_length(mchbar_base, channel, 256);
}

pub fn fill_pattern0(mchbar_base: usize, state: &RaminitState, channel: usize, a: u32, b: u32) {
    let offset = preceding_channels(state, channel) * 64;
    for j in 0..16usize {
        let val = if (j & 2) != 0 { b } else { a };
        write_pattern32(WDB_BASE + offset + 4 * j, val);
    }
    compiler_fence(Ordering::SeqCst);
    program_wdb_pattern_length(mchbar_base, channel, 8);
}

fn preceding_channels(state: &RaminitState, target_channel: usize) -> usize {
    (0..target_channel)
        .filter(|channel| state.topology.rankmap[*channel] != 0)
        .count()
}

fn num_channels(state: &RaminitState) -> usize {
    (0..2)
        .filter(|channel| state.topology.rankmap[*channel] != 0)
        .count()
}

fn program_wdb_pattern_length(mchbar_base: usize, channel: usize, num_cachelines: u16) {
    mchbar::write8(
        mchbar_base + cx(IOSAV_DATA_CTL_CH_BASE, channel),
        (num_cachelines / 8 - 1) as u8,
    );
}

fn write_pattern32(addr: usize, val: u32) {
    // SAFETY: coreboot uses this fixed WDB staging aperture during native raminit.
    unsafe { core::ptr::write_volatile(addr as *mut u32, val) }
}
