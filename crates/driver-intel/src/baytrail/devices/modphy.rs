/// SD card pad workaround in the south core community.
fn sdcard_pad_workaround() {
    let io = super::Bar(IO_BASE as usize);
    io.setbits32(0x698, 1 << 0);
    io.setbits32(0x698, 1 << 2);
    io.clrbits32(0x698, 1 << 1);
    io.clrbits32(0x690, 1 << 3);
    fstart_arch::x86::udelay(100);
    io.clrbits32(0x698, 1 << 0);
    fstart_arch::x86::udelay(100);
    io.write32(0x830, 0x78480);
    fstart_arch::x86::udelay(40);
    io.write32(0x830, 0x78080);
    io.setbits32(0x698, 1 << 0);
    fstart_arch::x86::udelay(100);
    io.setbits32(0x698, 1 << 1);
    io.clrbits32(0x698, 1 << 2);
    io.clrsetbits32(0x690, 7, 1 << 0);
}

