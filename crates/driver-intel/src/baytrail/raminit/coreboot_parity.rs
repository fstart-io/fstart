#[test]
fn init_matches_coreboot() {
    let sb = Sideband::default();
    // MPLL done flags set; compensation clears its start bit.
    sb.set(DDRIO, 0x7858, u32::MAX);
    sb.self_clearing(DDRIO, 0x6800, 1);
    let iosf = sb.iosf();
    let p = Params::new(&SPD_2GIB, DdrFreq::Ddr1333).unwrap();
    mc::program_timings(&iosf, &p);
    ddrio::init(&iosf, &p).unwrap();
    mc::pre_jedec(&iosf, &p);
    ddrio::pre_jedec(&iosf);
    mc::jedec_init(&iosf, &p);
    let ours: std::vec::Vec<std::string::String> = sb
        .log()
        .into_iter()
        .map(|(op, port, reg, data)| match op {
            OP_DRAM_INIT => std::format!("J {data:08x}"),
            OP_DRAM_WAKE => std::string::String::from("K wake 0"),
            _ => std::format!("W {port:02x} {reg:05x} {data:08x}"),
        })
        .collect();
    let reference: std::vec::Vec<&str> = include_str!("testdata/coreboot-ddr3-1333-init.txt")
        .lines()
        .collect();
    for (i, (a, b)) in ours.iter().zip(&reference).enumerate() {
        assert_eq!(a, b, "write {i} differs from coreboot");
    }
    assert_eq!(ours.len(), reference.len());
}
