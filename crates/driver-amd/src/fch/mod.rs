//! The FCH register layer every Family 17h SoC shares (ACPI MMIO,
//! PM, LPC, SMBus), and the
//! operations both Picasso and Zeppelin use. The common controllers have
//! their own modules: [`lpc`], [`spi`], [`espi`], [`emmc`], [`gpio`],
//! [`alink`], [`smi`] and the pre-console setup [`early`]. What the FCH
//! versions do differently is [`sandstone`] (Raven/Picasso, AGESA
//! FchSandstone) and [`taishan`] (Zeppelin, FchTaishan).
//!
//! Every FCH is reached through one handle, [`hw::FchHw`]: its register
//! spaces as windows ([`crate::window`]), FCH 0 of any SoC through
//! [`hw::Native`]. A register is defined once, as an [`At`] in its window:
//! the ACPI MMIO banks below ([`pm`], [`smi_bank`], ...) are offsets in
//! [`hw::FchHw::acpi`]. The access widths are those of the vendor code:
//! several of these registers have neighbours with side effects.
//!
//! ```ignore
//! fch.acpi().at(PM_DECODE).modify(Decode::CF9::SET);
//! ```
// tock's generated byte-register alignment assertions take remainder by one.
