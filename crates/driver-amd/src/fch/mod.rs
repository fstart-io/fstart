/// Native transport: MMIO, port I/O and, with `CONFIG`, ECAM byte-granular
/// config access. SMM uses [`SmmBus`]: the config spaces aren't decoded
/// there, reads return all ones and writes are dropped.
pub struct NativeBus<const CONFIG: bool = true> {
    _exclusive: PhantomData<*mut ()>,
}
pub type SmmBus = NativeBus<false>;
impl NativeBus {
    /// # Safety
    /// Ring 0, exclusive ownership of the FCH register spaces and index/data
    /// ports. Every touched MMIO range (ACPI MMIO of all dies, SPI,
    /// A-Link-to-AHB) is decoded and mapped UC. ECAM is published through
    /// `fstart_pci::ecam::init`.
    pub const unsafe fn new() -> Self {
        Self {
            _exclusive: PhantomData,
        }
    }
}
impl SmmBus {
    /// Only the MMIO and I/O spaces.
    /// # Safety
    /// As [`NativeBus::new`], without the ECAM.
    pub const unsafe fn without_config() -> Self {
        Self {
            _exclusive: PhantomData,
        }
    }
}
#[cfg(target_arch = "x86_64")]
impl<const CONFIG: bool> NativeBus<CONFIG> {
    #[inline(always)]
    fn config(space: Space) -> fstart_pci::EcamDevice {
        fstart_pci::EcamDevice::new(0, 0x14, if space == Space::Lpc { 3 } else { 0 })
    }
}
#[cfg(target_arch = "x86_64")]
impl<const CONFIG: bool> Bus for NativeBus<CONFIG> {
    #[inline(always)]
    fn read(&self, space: Space, address: u32, bytes: u8) -> u32 {
        use fstart_core::{mmio, pio};
        // SAFETY: the constructor's contract covers all four spaces.
        unsafe {
            match (space, bytes) {
                (Space::Mmio, 1) => mmio::read8(address as usize as *const u8).into(),
                (Space::Mmio, 2) => mmio::read16(address as usize as *const u16).into(),
                (Space::Mmio, _) => mmio::read32(address as usize as *const u32),
                (Space::Io, 1) => pio::inb(address as u16).into(),
                (Space::Io, 2) => pio::inw(address as u16).into(),
                (Space::Io, _) => pio::inl(address as u16),
                (Space::Lpc | Space::Smbus, _) if !CONFIG => u32::MAX,
                (Space::Lpc | Space::Smbus, 1) => Self::config(space).read8(address as u16).into(),
                (Space::Lpc | Space::Smbus, 2) => Self::config(space).read16(address as u16).into(),
                (Space::Lpc | Space::Smbus, _) => Self::config(space).read32(address as u16),
            }
        }
    }
    #[inline(always)]
    fn write(&self, space: Space, address: u32, bytes: u8, value: u32) {
        use fstart_core::{mmio, pio};
        // SAFETY: as for read.
        unsafe {
            match (space, bytes) {
                (Space::Mmio, 1) => mmio::write8(address as usize as *mut u8, value as u8),
                (Space::Mmio, 2) => mmio::write16(address as usize as *mut u16, value as u16),
                (Space::Mmio, _) => mmio::write32(address as usize as *mut u32, value),
                (Space::Io, 1) => pio::outb(address as u16, value as u8),
                (Space::Io, 2) => pio::outw(address as u16, value as u16),
                (Space::Io, _) => pio::outl(address as u16, value),
                (Space::Lpc | Space::Smbus, _) if !CONFIG => {}
                (Space::Lpc | Space::Smbus, 1) => {
                    Self::config(space).write8(address as u16, value as u8)
                }
                (Space::Lpc | Space::Smbus, 2) => {
                    Self::config(space).write16(address as u16, value as u16)
                }
                (Space::Lpc | Space::Smbus, _) => {
                    Self::config(space).write32(address as u16, value)
                }
            }
        }
    }
}

