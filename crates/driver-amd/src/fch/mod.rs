// ---- Register spaces ----

/// The register spaces of an FCH.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Space {
    /// Physical MMIO below 4 GiB: any die's ACPI MMIO, SPI, A-Link-to-AHB.
    Mmio,
    /// x86 I/O ports.
    Io,
    /// Config space of the LPC bridge D14F3.
    Lpc,
    /// Config space of the SMBus function D14F0.
    Smbus,
}

/// A register value width.
pub trait Value: UIntLike {
    const BYTES: u8;
    fn from_bus(value: u32) -> Self;
    fn to_bus(self) -> u32;
}
impl Value for u8 {
    const BYTES: u8 = 1;
    fn from_bus(value: u32) -> Self {
        value as u8
    }
    fn to_bus(self) -> u32 {
        self.into()
    }
}
impl Value for u16 {
    const BYTES: u8 = 2;
    fn from_bus(value: u32) -> Self {
        value as u16
    }
    fn to_bus(self) -> u32 {
        self.into()
    }
}
impl Value for u32 {
    const BYTES: u8 = 4;
    fn from_bus(value: u32) -> Self {
        value
    }
    fn to_bus(self) -> u32 {
        self
    }
}

/// A register of width `T` with tock bitfields `R` in one of the [`Space`]s.
pub struct Reg<T, R = ()> {
    pub space: Space,
    pub address: u32,
    _type: PhantomData<fn() -> (T, R)>,
}
impl<T, R> Clone for Reg<T, R> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<T, R> Copy for Reg<T, R> {}
impl<T: Value, R: RegisterLongName> Reg<T, R> {
    pub const fn new(space: Space, address: u32) -> Self {
        Self {
            space,
            address,
            _type: PhantomData,
        }
    }
    pub const fn mmio(address: u32) -> Self {
        Self::new(Space::Mmio, address)
    }
    pub const fn io(port: u16) -> Self {
        Self::new(Space::Io, port as u32)
    }
    pub const fn lpc(offset: u16) -> Self {
        Self::new(Space::Lpc, offset as u32)
    }
    pub const fn smbus(offset: u16) -> Self {
        Self::new(Space::Smbus, offset as u32)
    }
}

/// The POST code port, which the FCH forwards to LPC/eSPI (a BMC's POST
/// snoop, a debug card).
pub const POST_CODE: Reg<u8> = Reg::io(0x80);

/// Carries the accesses of the FCH register spaces.
pub trait Bus {
    fn read(&self, space: Space, address: u32, bytes: u8) -> u32;
    fn write(&self, space: Space, address: u32, bytes: u8, value: u32);

    /// `reg` as a tock register.
    fn reg<T: Value, R: RegisterLongName>(&self, reg: Reg<T, R>) -> BusRegister<'_, Self, T, R>
    where
        Self: Sized,
    {
        BusRegister { bus: self, reg }
    }
}
impl<B: Bus> Bus for &B {
    fn read(&self, space: Space, address: u32, bytes: u8) -> u32 {
        (**self).read(space, address, bytes)
    }
    fn write(&self, space: Space, address: u32, bytes: u8, value: u32) {
        (**self).write(space, address, bytes, value)
    }
}

/// A [`Reg`] on a [`Bus`].
pub struct BusRegister<'a, B, T, R> {
    bus: &'a B,
    reg: Reg<T, R>,
}
impl<B, T, R> Clone for BusRegister<'_, B, T, R> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<B, T, R> Copy for BusRegister<'_, B, T, R> {}
impl<B: Bus, T: Value, R: RegisterLongName> Readable for BusRegister<'_, B, T, R> {
    type T = T;
    type R = R;
    #[inline(always)]
    fn get(&self) -> T {
        T::from_bus(self.bus.read(self.reg.space, self.reg.address, T::BYTES))
    }
}
impl<B: Bus, T: Value, R: RegisterLongName> Writeable for BusRegister<'_, B, T, R> {
    type T = T;
    type R = R;
    #[inline(always)]
    fn set(&self, value: T) {
        self.bus
            .write(self.reg.space, self.reg.address, T::BYTES, value.to_bus());
    }
}

/// An 8-bit register behind an I/O index/data pair (`data = index + 1`).
pub type IndexedIo<'a, B, R = ()> =
    Indexed<BusRegister<'a, B, u8, ()>, BusRegister<'a, B, u8, ()>, R>;
pub fn indexed_io<B: Bus, R: RegisterLongName>(bus: &B, index: u16, at: u8) -> IndexedIo<'_, B, R> {
    Indexed::new(bus.reg(Reg::io(index)), bus.reg(Reg::io(index + 1)), at)
}

