#[derive(Debug, PartialEq, Eq)]
pub enum Error {
    InvalidDevice,
    PowerTimeout(u8),
    Unavailable(u8),
}
fn valid_device(device: u8) -> bool {
    matches!(device, 0 | 7..=9 | 11..=12 | 16..=17 | 26..=28)
}

/// One die's FCH: its ACPI MMIO block on a [`Bus`].
pub struct Fch<B> {
    bus: B,
    acpimmio: Acpimmio,
}
impl<B: Bus> Fch<B> {
    pub const fn new(bus: B, acpimmio: Acpimmio) -> Self {
        Self { bus, acpimmio }
    }
    pub fn bus(&self) -> &B {
        &self.bus
    }
    pub const fn acpimmio(&self) -> Acpimmio {
        self.acpimmio
    }
    /// A register of the ACPI MMIO block.
    pub fn reg<T: Value, R: RegisterLongName>(
        &self,
        reg: AcpiReg<T, R>,
    ) -> BusRegister<'_, B, T, R> {
        self.bus.reg(self.acpimmio.reg(reg))
    }
    /// Apply a vendor ACPI MMIO table ([`crate::table`]) in order.
    pub fn apply<T: Value>(&self, records: impl IntoIterator<Item = Record<AcpiReg<T>, T>>) {
        table::apply(records, |reg| self.reg(reg));
    }

    /// Validate all devices/controls before power writes. Start every device
    /// before waiting; all-ones is unavailable, not a proof that power/clock
    /// are ready. After any programming error the caller must stop/reset, not
    /// retry. Polling is bounded, `polls` times 100 us.
    pub fn power_devices(
        &self,
        devices: &[u8],
        polls: u32,
        delay: &mut impl DelayNs,
    ) -> Result<(), Error> {
        if devices.iter().any(|&id| !valid_device(id)) {
            return Err(Error::InvalidDevice);
        }
        let mut controls = [0; 29];
        for &id in devices {
            let control = self.reg(aoac_control(id)).get();
            if control == u8::MAX {
                return Err(Error::Unavailable(id));
            }
            controls[usize::from(id)] = control;
        }
        for &id in devices {
            let mut control =
                LocalRegisterCopy::<u8, AoacControl::Register>::new(controls[usize::from(id)]);
            control.modify(AoacControl::POWER::SET + AoacControl::TARGET::Initialized);
            self.reg(aoac_control(id)).set(control.get());
        }
        for &id in devices {
            let mut remaining = polls;
            loop {
                let state = self.reg(aoac_state(id)).extract();
                if state.get() == u8::MAX {
                    return Err(Error::Unavailable(id));
                }
                if state.matches_all(AoacState::POWER_RESET::SET + AoacState::REFERENCE_CLOCK::SET)
                {
                    break;
                }
                if remaining == 0 {
                    return Err(Error::PowerTimeout(id));
                }
                delay.delay_us(100);
                remaining -= 1;
            }
        }
        Ok(())
    }
    /// Range_0 defaults enabled. No legacy aliases for the MMIO UART.
    pub fn clear_legacy_uart_decode(&self) {
        self.bus.reg(LEGACY_UART_DECODE).set(0);
    }
    pub fn enable_legacy_decode(&self) {
        self.reg(PM_DECODE)
            .modify(Decode::LEGACY::SET + Decode::CF9::SET);
    }
    pub fn disable_legacy_dma(&self) {
        self.reg(PM_DECODE)
            .modify(Decode::DMA::CLEAR + Decode::DMA80::CLEAR);
    }
    pub fn enable_hpet_ioapic(&self) {
        self.reg(PM_DECODE).modify(
            Decode::IOAPIC::SET + Decode::HPET::SET + Decode::HPET_MSI::SET + Decode::HPET64::CLEAR,
        );
    }
    /// fch_init_acpi_decode: the ACPI blocks and their standard decode.
    pub fn acpi_decode(&self, ports: AcpiPorts) {
        self.reg(PM_ACPI_PM1_EVT).set(ports.event);
        self.reg(PM_ACPI_PM1_CNT).set(ports.control);
        self.reg(PM_ACPI_PM_TMR).set(ports.timer);
        self.reg(PM_ACPI_GPE0).set(ports.gpe);
        self.reg(PM_ACPI_CONFIG).modify(AcpiConfig::DECODE_STD::SET);
    }
    /// fch_init_acpi_ports: the ACPI blocks and the standard features. The SMI
    /// command port belongs to [`smi::FchSmi`].
    pub fn acpi_ports(&self, ports: AcpiPorts) {
        self.acpi_decode(ports);
        self.reg(PM_ACPI_CONFIG).write(
            AcpiConfig::DECODE_STD::SET
                + AcpiConfig::GLOBAL_EN::SET
                + AcpiConfig::RTC_EN_EN::SET
                + AcpiConfig::TIMER_EN_EN::SET,
        );
    }
    pub fn disable_keyboard_reset(&self) {
        self.reg(PM_RESET_CONTROL1)
            .modify(ResetControl1::KB_RESET_EN::CLEAR);
    }
    /// The legacy SD controller off: its decode and its AOAC power.
    pub fn legacy_sd_off(&self) {
        self.reg(PM_SD_CONTROL).modify(SdControl::LEGACY_SD::CLEAR);
        self.reg(PM_SD_ENABLE).modify(SdEnable::ENABLE::CLEAR);
        self.reg(aoac_control(AOAC_LEGACY_SD))
            .modify(AoacControl::POWER::CLEAR);
    }
}

