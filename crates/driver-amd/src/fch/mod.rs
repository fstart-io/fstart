/// A register of the ACPI MMIO block, at an offset from its base.
pub struct AcpiReg<T, R = ()> {
    offset: u32,
    _type: PhantomData<fn() -> (T, R)>,
}
impl<T, R> Clone for AcpiReg<T, R> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<T, R> Copy for AcpiReg<T, R> {}
impl<T: Value, R: RegisterLongName> AcpiReg<T, R> {
    pub const fn new(offset: u32) -> Self {
        Self {
            offset,
            _type: PhantomData,
        }
    }
    pub const fn offset(self) -> u32 {
        self.offset
    }
}

/// The ACPI MMIO block of one die's FCH.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Acpimmio(pub u32);
impl Acpimmio {
    pub const DIE0: Self = Self(ACPI_MMIO);
    pub const fn reg<T: Value, R: RegisterLongName>(self, reg: AcpiReg<T, R>) -> Reg<T, R> {
        Reg::mmio(self.0 + reg.offset)
    }
}

/// The ACPI MMIO banks and their registers. `at` gives a register of a bank
/// by its offset, for the vendor tables whose bits have no known meaning.
macro_rules! bank {
    ($(#[$meta:meta])* $name:ident, $base:expr) => {
        $(#[$meta])*
        pub mod $name {
            use super::{AcpiReg, Value};
            use tock_registers::RegisterLongName;
            pub const BASE: u32 = $base;
            pub const fn at<T: Value, R: RegisterLongName>(offset: u32) -> AcpiReg<T, R> {
                AcpiReg::new(BASE + offset)
            }
        }
    };
}
