/// Board choices for the FCH devices of a die. Die 0's xHCI is always set
/// up.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Devices {
    pub xhci: bool,
    pub sata: bool,
}

/// The register spaces the FCH init touches.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Space {
    /// Physical MMIO below 4 GiB: any die's ACPI MMIO, SPI, A-Link-to-AHB.
    Mmio,
    /// x86 I/O ports.
    Io,
    /// Config space of the LPC bridge D14F3.
    Lpc,
    /// Config space of the SMBus function D14F0.
    Smbus,
}

/// A register value width.
pub trait Value: UIntLike {
    const BYTES: u8;
    fn from_bus(value: u32) -> Self;
    fn to_bus(self) -> u32;
}
impl Value for u8 {
    const BYTES: u8 = 1;
    fn from_bus(value: u32) -> Self {
        value as u8
    }
    fn to_bus(self) -> u32 {
        self.into()
    }
}
impl Value for u16 {
    const BYTES: u8 = 2;
    fn from_bus(value: u32) -> Self {
        value as u16
    }
    fn to_bus(self) -> u32 {
        self.into()
    }
}
impl Value for u32 {
    const BYTES: u8 = 4;
    fn from_bus(value: u32) -> Self {
        value
    }
    fn to_bus(self) -> u32 {
        self
    }
}

/// A register of width `T` with tock bitfields `R` in one of the [`Space`]s.
pub struct Reg<T, R = ()> {
    pub space: Space,
    pub address: u32,
    _type: PhantomData<fn() -> (T, R)>,
}
impl<T, R> Clone for Reg<T, R> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<T, R> Copy for Reg<T, R> {}
impl<T: Value, R: RegisterLongName> Reg<T, R> {
    pub const fn new(space: Space, address: u32) -> Self {
        Self {
            space,
            address,
            _type: PhantomData,
        }
    }
    pub const fn mmio(address: u32) -> Self {
        Self::new(Space::Mmio, address)
    }
    pub const fn io(port: u16) -> Self {
        Self::new(Space::Io, port as u32)
    }
    pub const fn lpc(offset: u16) -> Self {
        Self::new(Space::Lpc, offset as u32)
    }
}

/// Register transport of the FCH. The access widths are those of the vendor
/// code: several of these registers have neighbours with side effects.
pub trait Bus {
    fn read(&mut self, space: Space, address: u32, bytes: u8) -> u32;
    fn write(&mut self, space: Space, address: u32, bytes: u8, value: u32);

    fn get<T: Value, R: RegisterLongName>(&mut self, reg: Reg<T, R>) -> LocalRegisterCopy<T, R> {
        LocalRegisterCopy::new(T::from_bus(self.read(reg.space, reg.address, T::BYTES)))
    }
    fn set<T: Value, R: RegisterLongName>(&mut self, reg: Reg<T, R>, value: T) {
        self.write(reg.space, reg.address, T::BYTES, value.to_bus());
    }
    /// Read, clear `clear`, set `set`, write.
    fn update<T: Value, R: RegisterLongName>(&mut self, reg: Reg<T, R>, clear: T, set: T) {
        let value = self.get(reg).get();
        self.set(reg, (value & !clear) | set);
    }
    fn modify<T: Value, R: RegisterLongName>(&mut self, reg: Reg<T, R>, field: FieldValue<T, R>) {
        let value = self.get(reg).get();
        self.set(reg, field.modify(value));
    }
}

/// An 8-bit register behind an I/O index/data pair (`data = index + 1`).
fn index_read(bus: &mut impl Bus, index_port: u16, index: u8) -> u8 {
    bus.set(Reg::<u8>::io(index_port), index);
    bus.get(Reg::<u8>::io(index_port + 1)).get()
}
fn index_write(bus: &mut impl Bus, index_port: u16, index: u8, value: u8) {
    bus.set(Reg::<u8>::io(index_port), index);
    bus.set(Reg::<u8>::io(index_port + 1), value);
}

/// Legacy PM index/data I/O; reaches whichever FCH the DF routes I/O to.
const PM_INDEX: u16 = 0xcd6;
/// A-Link (AB) index/data I/O, decoded where PMxE0 says.
const AB_INDEX: u16 = 0xcd8;
const AB_DATA: u16 = 0xcdc;
/// SMBus/ASF I/O (PMx00[15:8]).
const SMBUS_IO: u16 = super::SMBUS_IO;
const ASF_IO: u16 = SMBUS_IO + 0x20;
/// CMOS bank 0 index/data.
const RTC_INDEX: u16 = 0x70;
/// A-Link-to-AHB bridge and its AHB devices.
const AL2AHB: u32 = 0xfedc_0000;

tock_registers::register_bitfields![u32,
    /// A-Link index: register space in [31:29].
    AbIndex [ADDRESS OFFSET(0) NUMBITS(29) [], SPACE OFFSET(29) NUMBITS(3) [Abcfg = 6]]
];
/// ABCFG read-modify-write with the index cleared between the halves
/// (RPR 4.2: required for the 0x100NN registers).
fn abcfg_update(bus: &mut impl Bus, register: u32, clear: u32, set: u32) {
    let index = (AbIndex::SPACE::Abcfg + AbIndex::ADDRESS.val(register)).value;
    bus.set(Reg::<u32>::io(AB_INDEX), index);
    let value = bus.get(Reg::<u32>::io(AB_DATA)).get();
    bus.set(Reg::<u32>::io(AB_INDEX), 0);
    bus.set(Reg::<u32>::io(AB_INDEX), index);
    bus.set(Reg::<u32>::io(AB_DATA), (value & !clear) | set);
    bus.set(Reg::<u32>::io(AB_INDEX), 0);
}

/// The ACPI MMIO block of one die's FCH.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Acpimmio(pub u32);
impl Acpimmio {
    pub const DIE0: Self = Self(crate::ACPI_MMIO as u32);
    const fn bank<T: Value, R: RegisterLongName>(self, bank: u32, offset: u32) -> Reg<T, R> {
        Reg::mmio(self.0 + bank + offset)
    }
    pub const fn smi<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0x200, offset)
    }
    pub const fn pm<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0x300, offset)
    }
    pub const fn smbus<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0xa00, offset)
    }
    pub const fn iomux<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0xd00, offset)
    }
    /// The ACPI registers (PM1 status/enable at 0/2).
    pub const fn acpi<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0x800, offset)
    }
    /// GPIO bank 0: the control register of pin n at 4 * n.
    pub const fn gpio<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0x1500, offset)
    }
    pub const fn misc<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0xe00, offset)
    }
    pub const fn aoac<T: Value, R: RegisterLongName>(self, offset: u32) -> Reg<T, R> {
        self.bank(0x1e00, offset)
    }
    /// The AOAC D3 control of a device.
    pub const fn aoac_control(self, device: u8) -> Reg<u8, crate::fch::AoacControl::Register> {
        self.aoac(0x40 + 2 * device as u32)
    }
}

/// The legacy SD controller off: PMxD3[6], PMxE8[0] and its AOAC power.
fn legacy_sd_off(bus: &mut impl Bus, mmio: Acpimmio) {
    const AOAC_LEGACY_SD: u8 = 0x19;
    bus.update(mmio.pm::<u8, ()>(0xd3), 1 << 6, 0);
    bus.update(mmio.pm::<u8, ()>(0xe8), 1, 0);
    bus.modify(
        mmio.aoac_control(AOAC_LEGACY_SD),
        crate::fch::AoacControl::POWER::CLEAR,
    );
}

/// Read-clear-set of an SMN register with tock fields.
fn smn_modify<R: RegisterLongName>(smn: &mut impl Smn, address: u32, field: FieldValue<u32, R>) {
    smn.update(address, field.mask(), field.value);
}

/// Native transport: MMIO, port I/O and ECAM byte-granular config access.
pub struct NativeBus {
    _exclusive: PhantomData<*mut ()>,
}
impl NativeBus {
    /// # Safety
    /// Ring 0, BSP only, exclusive ownership of the FCH register spaces and
    /// index/data ports. ECAM is published through `fstart_pci::ecam::init`,
    /// every touched MMIO range (ACPI MMIO of all dies, SPI, A-Link-to-AHB)
    /// is decoded and mapped UC.
    pub unsafe fn new() -> Self {
        Self {
            _exclusive: PhantomData,
        }
    }
}
#[cfg(target_arch = "x86_64")]
impl Bus for NativeBus {
    fn read(&mut self, space: Space, address: u32, bytes: u8) -> u32 {
        use fstart_core::{mmio, pio};
        let pci = |device| fstart_pci::EcamDevice::new(0, 0x14, device);
        // SAFETY: the constructor's contract covers all four spaces.
        unsafe {
            match (space, bytes) {
                (Space::Mmio, 1) => mmio::read8(address as usize as *const u8).into(),
                (Space::Mmio, 2) => mmio::read16(address as usize as *const u16).into(),
                (Space::Mmio, _) => mmio::read32(address as usize as *const u32),
                (Space::Io, 1) => pio::inb(address as u16).into(),
                (Space::Io, 2) => pio::inw(address as u16).into(),
                (Space::Io, _) => pio::inl(address as u16),
                (Space::Lpc | Space::Smbus, _) => {
                    let device = pci(if space == Space::Lpc { 3 } else { 0 });
                    let offset = address as u16;
                    match bytes {
                        1 => device.read8(offset).into(),
                        2 => device.read16(offset).into(),
                        _ => device.read32(offset),
                    }
                }
            }
        }
    }
    fn write(&mut self, space: Space, address: u32, bytes: u8, value: u32) {
        use fstart_core::{mmio, pio};
        let pci = |device| fstart_pci::EcamDevice::new(0, 0x14, device);
        // SAFETY: as for read.
        unsafe {
            match (space, bytes) {
                (Space::Mmio, 1) => mmio::write8(address as usize as *mut u8, value as u8),
                (Space::Mmio, 2) => mmio::write16(address as usize as *mut u16, value as u16),
                (Space::Mmio, _) => mmio::write32(address as usize as *mut u32, value),
                (Space::Io, 1) => pio::outb(address as u16, value as u8),
                (Space::Io, 2) => pio::outw(address as u16, value as u16),
                (Space::Io, _) => pio::outl(address as u16, value),
                (Space::Lpc | Space::Smbus, _) => {
                    let device = pci(if space == Space::Lpc { 3 } else { 0 });
                    let offset = address as u16;
                    match bytes {
                        1 => device.write8(offset, value as u8),
                        2 => device.write16(offset, value as u16),
                        _ => device.write32(offset, value),
                    }
                }
            }
        }
    }
}

