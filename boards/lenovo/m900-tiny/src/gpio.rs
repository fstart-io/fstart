//! Exact M900 Tiny pad policy from mainboard/lenovo/m900_tiny/gpio.c.
//! The full table preserves source order, reset/pull/ownership and interrupt
//! routes. Callers still own PMC/community GPE selection and ACPI event
//! delivery; this fact table does not initialize stages. No pad is omitted.

use fstart_driver_intel::sunrise_point::{
    gpio::{Group, Pad, PadConfig},
    gpio_config::{self as cfg, NativeFunction, Owner, Pull, Reset, Route, Trigger},
};

const fn pad(group: Group, pin: u8) -> Pad {
    match group.pad(pin) {
        Ok(pad) => pad,
        Err(_) => panic!("invalid source board pad"),
    }
}

